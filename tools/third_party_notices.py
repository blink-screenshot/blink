"""Writes THIRD-PARTY-NOTICES.md: every Rust crate that ends up in the Windows build, its
license, and the license or copyright text it ships, plus the assets that are not crates.

    python tools/third_party_notices.py

Run it after changing dependencies (CI checks that the file is up to date). It needs only
cargo and the crate sources cargo has already downloaded (`cargo fetch`).
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
TARGET = "x86_64-pc-windows-msvc"

# Long, standard license texts are included once instead of once per crate.
SHARED = ("Apache-2.0", "MPL-2.0")
NAMES = ("license", "licence", "copying", "notice", "copyright", "authors")

ASSETS = """\
## Assets that are not Rust crates

- **Twemoji** (emoji stamps, `assets/emoji/`). Graphics copyright 2019 Twitter, Inc. and other
  contributors, licensed under [CC-BY 4.0](https://creativecommons.org/licenses/by/4.0/).
  Source: https://github.com/jdecked/twemoji
- **devices.css** (proportions of the device mockups, redrawn as vectors). Copyright (c) Yan Zhu,
  MIT license. Source: https://github.com/picturepan2/devices.css
"""


def main() -> int:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            cwd=ROOT,
        )
    )
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]

    # Only what is linked into the program: skip dev- and build-dependencies.
    seen, todo = set(), [root]
    while todo:
        cur = todo.pop()
        for dep in nodes[cur]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds & {None, "normal"} and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])

    crates = sorted((pkgs[i] for i in seen), key=lambda p: (p["name"], p["version"]))
    out = [
        "# Third-party notices",
        "",
        "Blink is licensed under the GNU General Public License v3.0 or later (see `LICENSE`).",
        "It includes the open-source components below, under their own licenses.",
        "This file is generated by `tools/third_party_notices.py`; do not edit it by hand.",
        "",
        ASSETS,
        "## Rust crates",
        "",
        "| Crate | Version | License |",
        "|---|---|---|",
    ]
    for p in crates:
        out.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see below'} |")
    out += ["", "## License and copyright texts", ""]
    for p in crates:
        lic = p.get("license") or ""
        folder = pathlib.Path(p["manifest_path"]).parent
        files = sorted(
            f for f in folder.iterdir() if f.is_file() and f.name.lower().startswith(NAMES)
        )
        texts = []
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").strip()
            head = text[:400].lower()
            # Skip full standard texts that are included once at the end.
            if "apache license" in head and "version 2.0" in head:
                continue
            if "mozilla public license" in head:
                continue
            texts.append((f.name, text))
        out.append(f"### {p['name']} {p['version']}")
        out.append("")
        out.append(f"License: {lic or 'unknown'}" + (f". Source: {p['repository']}" if p.get("repository") else ""))
        out.append("")
        for name, text in texts:
            out += [f"`{name}`:", "", "```text", text, "```", ""]
        if not texts and not any(s in lic for s in SHARED):
            out += ["(No license file in the crate; see the source repository.)", ""]
    out += ["## Full texts of shared licenses", ""]
    for spdx in SHARED:
        path = ROOT / "tools" / "licenses" / f"{spdx}.txt"
        out += [f"### {spdx}", "", "```text", path.read_text(encoding="utf-8").strip(), "```", ""]

    text = "\n".join(out).rstrip() + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("THIRD-PARTY-NOTICES.md is out of date: run python tools/third_party_notices.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.name}: {len(crates)} crates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
